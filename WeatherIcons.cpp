uint16_t getIconColor(const String& iconCode) {
  if (iconCode.startsWith("01") || iconCode.startsWith("02")) {
    return getScaledColor(255, 255, 0);
  } else if (iconCode.startsWith("03") || iconCode.startsWith("04") || iconCode.endsWith("n")) {
    return getScaledColor(255, 255, 255);
  } else if (iconCode.startsWith("09") || iconCode.startsWith("10") ||
             iconCode.startsWith("11") || iconCode.startsWith("13")) {
    return getScaledColor(0, 128, 255);
  }
  return getScaledColor(192, 192, 192);
}

void drawWeatherIcon(const String& iconCode, int x, int y) {
  if (iconCode.startsWith("01")) {
    matrix.drawBitmap(x + 10, y + 12, bitmap_sun, 24, 24, getScaledColor(255, 255, 0));
    return;
  } else if (iconCode.startsWith("02")) {
    matrix.drawBitmap(x + 3, y + 5, bitmap_partial_sun, 32, 32, getScaledColor(255, 255, 0));
    matrix.drawBitmap(x + 4, y + 5, bitmap_few_clouds, 32, 32, getScaledColor(255, 255, 255));
    return;
  } else if (iconCode.startsWith("03")) {
    matrix.drawBitmap(x, y, bitmap_cloud, 40, 40, getScaledColor(255, 255, 255));
    return;
  } else if (iconCode.startsWith("04")) {
    matrix.drawBitmap(x + 5, y + 5, bitmap_broken_clouds_black, 32, 32, getScaledColor(120, 120, 120));
    matrix.drawBitmap(x + 5, y + 5, bitmap_broken_clouds, 32, 32, getScaledColor(255, 255, 255));
    return;
  } else if (iconCode.startsWith("09")) {
    matrix.drawBitmap(x + 5, y + 5, bitmap_broken_clouds_black, 32, 32, getScaledColor(120, 120, 120));
    matrix.drawBitmap(x + 5, y + 5, bitmap_broken_clouds, 32, 32, getScaledColor(255, 255, 255));
    matrix.drawBitmap(x - 3, y + 15, bitmap_rain, 32, 32, getScaledColor(0, 0, 255));
    return;
  } else if (iconCode.startsWith("10")) {
    matrix.drawBitmap(x + 3, y + 5, bitmap_partial_sun, 32, 32, getScaledColor(255, 255, 0));
    matrix.drawBitmap(x + 4, y + 5, bitmap_few_clouds, 32, 32, getScaledColor(255, 255, 255));
    matrix.drawBitmap(x - 3, y + 15, bitmap_rain, 32, 32, getScaledColor(0, 0, 255));
    return;
  } else if (iconCode.startsWith("11")) {
    matrix.drawBitmap(x + 5, y + 4, bitmap_broken_clouds_black, 32, 32, getScaledColor(120, 120, 120));
    matrix.drawBitmap(x + 5, y + 4, bitmap_broken_clouds, 32, 32, getScaledColor(255, 255, 255));
    matrix.drawBitmap(x + 7, y + 10, bitmap_lightning, 32, 32, getScaledColor(255, 255, 0));
    return;
  } else if (iconCode.startsWith("13")) {
    matrix.drawBitmap(x + 3, y + 7, bitmap_snow, 32, 32, getScaledColor(255, 255, 255));
    return;
  } else if (iconCode.startsWith("50")) {
    matrix.drawBitmap(x + 3, y + 3, bitmap_mist, 32, 32, getScaledColor(255, 255, 255));
    return;
  }

  matrix.setCursor(x, y);
  matrix.setTextColor(getScaledColor(192, 192, 192));
  matrix.print("?");
}
